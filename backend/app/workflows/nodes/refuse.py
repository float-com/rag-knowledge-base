"""refuse：统一拒答终结节点（收敛出口设计）。

【模块核心职责】：
系统级**唯一法定**的拒答文案与状态落笔处。
工作流中所有裁定需要安全熔断的分支，最终均重定向汇聚至本节点统一闭环收口。

【为什么拒绝在各判定节点“原地写入”？】：
在此架构演进前，拒答逻辑散落在多处（如意图路由拦截、检索层熔断、质量判决不达标），各自就地填报拒答内容：
- 文案维护成本高：业务调整预置话术时多处同步，极易遗漏引发不一致；
- 观测性埋点分散：增设拒答告警、指标度量（Metrics）与审计日志时需重复侵入多处逻辑；
- 契约语义漂移风险：多处自行组装状态极易导致字段规范脱节。
抽象出单一出口节点后，实现了**“判定与执行解耦”**，收敛了副作用范围。

【关键设计哲学：“决策判定”与“执行动作”分立】：
- 本节点专职负责【执行动作】：纯粹完成状态置位与文本装配。
- 业务系统保留两处【判定决策】（业务属性不同，合理共存）：
  ① 意图路由层（plan_retrieval）判定：问题超出业务域/无需检索（如闲聊、超纲实时问题）；
  ② 质量仲裁层（judge_context）判定：虽允许检索，但检索到的切片置信度未达安全阈值。
决策归决策，动作归一处。
"""

# 引入系统标准拒答文案常量（单点维护安全话术）
from app.llm.prompts import REFUSAL_ANSWER
# 引入 RAG 工作流状态契约规范
from app.workflows.rag_state import RAGState


async def refuse(state: RAGState) -> RAGState:
    """执行标准拒答操作：原子化写入拒答状态标志与展示文案。

    【字段双写的必要性与契约对齐】：
    1. `refused: True`（控制面信号）：供下游服务层与网关快速分流（判断短路，跳过后续大模型生成调用，节省算力开销）；
    2. `answer: REFUSAL_ANSWER`（数据面内容）：供数据库持久化落库与前端最终渲染展示。
    两个字段作为原子契约共同下发，彻底杜绝“有状态无文本”或“有文案未置标志位”的状态错位隐患。

    :param state: 工作流当前状态（本节点作为终结输出节点，不读取上游任何业务字段）
    :return: 增量状态字典，包含原子绑定的 refused 与 answer
    """
    return {"refused": True, "answer": REFUSAL_ANSWER}